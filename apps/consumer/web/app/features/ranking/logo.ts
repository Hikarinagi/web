const CAP_SCALE = 0.3
const BADGE_PAD = 17
export const BADGE_HEIGHT = 50

export function badgeOf(text: string) {
  let x = CAP_STROKE / 2
  const letters = [...text].map(char => {
    const glyph = CAPS[char]!
    const at = x
    x += glyph.w + CAP_STROKE + CAP_GAP
    return { d: glyph.d, transform: `translate(${at} ${CAP_STROKE / 2})` }
  })
  const width = (x - CAP_GAP - CAP_STROKE / 2) * CAP_SCALE
  return {
    letters,
    width: width + BADGE_PAD * 2,
    inner: `translate(${BADGE_PAD} ${(BADGE_HEIGHT - (80 + CAP_STROKE) * CAP_SCALE) / 2}) scale(${CAP_SCALE})`,
  }
}
